                            <h2>Who Needs a Knee Replacement?</h2>
                            <p>
                                Age alone does not decide whether you need surgery. The decision depends on how much the knee damage affects your daily life and whether other treatments have stopped working.
                            </p>

                            <h3>Common conditions that lead to knee replacement</h3>
                            <div class="symptoms-grid">
                                <div class="symptom-card">
                                    <div class="symptom-icon"><i class="fas fa-bone"></i></div>
                                    <div class="symptom-info">
                                        <h4>Osteoarthritis</h4>
                                        <p>The wear-and-tear arthritis that is the most common reason, especially after 55.</p>
                                    </div>
                                </div>
                                <div class="symptom-card">
                                    <div class="symptom-icon"><i class="fas fa-fire-alt"></i></div>
                                    <div class="symptom-info">
                                        <h4>Rheumatoid Arthritis</h4>
                                        <p>An inflammatory condition that damages the joint lining.</p>
                                    </div>
                                </div>
                                <div class="symptom-card">
                                    <div class="symptom-icon"><i class="fas fa-band-aid"></i></div>
                                    <div class="symptom-info">
                                        <h4>Post-traumatic Arthritis</h4>
                                        <p>Follows an old fracture or ligament injury.</p>
                                    </div>
                                </div>
                                <div class="symptom-card">
                                    <div class="symptom-icon"><i class="fas fa-walking"></i></div>
                                    <div class="symptom-info">
                                        <h4>Knee Deformities</h4>
                                        <p>Bow legs or knock knees caused by arthritis.</p>
                                    </div>
                                </div>
                            </div>

