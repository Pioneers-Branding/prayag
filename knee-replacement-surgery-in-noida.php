                                    <h4>Right After Surgery</h4>
                                    <ul>
                                        <li>Pain is managed with medicines so you can begin moving early.</li>
                                        <li>Most patients stand and take a few steps with a walker within a day of surgery, under a physiotherapist's guidance.</li>
                                        <li>The usual hospital stay is around three to five days, depending on your recovery and overall health.</li>
                                    </ul>
                                </div>
