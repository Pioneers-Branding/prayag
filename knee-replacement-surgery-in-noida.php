                        <!-- Section: What Is Knee Replacement -->
                        <section id="what-is-knee-replacement" class="article-section">
                            <h2>What Is Knee Replacement Surgery?</h2>
                            <p>
                                In knee replacement surgery, also called <strong>knee arthroplasty</strong>, the surgeon removes the damaged bone and cartilage from the knee joint and replaces it with an artificial joint (implant) made of metal and medical-grade plastic. The implant recreates the smooth, gliding surface of a healthy knee, so the bones no longer grind against each other.
                            </p>
                            <p>There are two main types:</p>

                            <div class="comparison-table-wrapper">
                                <table class="comparison-table">
                                    <thead>
                                        <tr>
                                            <th>Type</th>
                                            <th>What is replaced</th>
                                            <th>Suited for</th>
                                        </tr>
                                    </thead>
                                    <tbody>
                                        <tr>
                                            <td><strong>Total knee replacement (TKR)</strong></td>
                                            <td>All three compartments of the knee joint</td>
                                            <td>Advanced arthritis affecting the whole knee; the most common type</td>
                                        </tr>
                                        <tr>
                                            <td><strong>Partial knee replacement</strong></td>
                                            <td>Only the damaged part of the knee</td>
                                            <td>Damage limited to one area, with healthy ligaments</td>
                                        </tr>
                                    </tbody>
                                </table>
                            </div>

                            <p>
                                Your orthopaedic surgeon will recommend the right option after examining your knee and reviewing X-rays or other scans.
                            </p>
                        </section>

