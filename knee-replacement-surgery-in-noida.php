                        <section id="what-to-expect" class="article-section">
                            <h2>What to Expect: Before, During and After Surgery</h2>

                            <div class="treatment-flow-grid">
                                <div class="flow-card">
                                    <div class="flow-icon icon-before"><i class="fas fa-clipboard-list"></i></div>
                                    <h4>Before Surgery</h4>
                                    <ul>
                                        <li><strong>Evaluation:</strong> a detailed examination, X-rays and, if needed, other scans of the knee.</li>
                                        <li><strong>Pre-operative tests:</strong> blood tests, ECG and a check of heart, lung, sugar and blood pressure levels to make sure you are fit for surgery.</li>
                                        <li><strong>Medicine review:</strong> your doctor may adjust medicines such as blood thinners before surgery.</li>
                                        <li><strong>Home preparation:</strong> keep frequently used items within reach, remove loose rugs, and arrange for a family member to help for the first few weeks. A raised toilet seat and grab bars in the bathroom are helpful.</li>
                                    </ul>
                                </div>
                                <div class="flow-card">
                                    <div class="flow-icon icon-during"><i class="fas fa-procedures"></i></div>
                                    <h4>During Surgery</h4>
                                    <ul>
                                        <li>The surgery usually takes about one and a half to two hours.</li>
                                        <li>It is done under spinal or general anaesthesia, so you will not feel pain during the procedure.</li>
                                        <li>The surgeon removes the damaged surfaces of the thigh bone, shin bone and sometimes the kneecap, then fixes the implant in place.</li>
                                    </ul>
                                </div>
