                        <!-- Section: Signs You Should See a Gynaecologist -->
                        <section id="signs-to-see-gynaecologist" class="article-section">
                            <h2>Signs You Should See a Gynaecologist</h2>
                            <p>
                                If you experience any of the following symptoms, scheduling a consultation with a gynaecologist can provide clarity and relief:
                            </p>

                            <div class="signs-grid">
                                <div class="sign-card">
                                    <div class="sign-header">
                                        <div class="sign-icon"><i class="fas fa-calendar-times"></i></div>
                                        <h3 class="sign-title">Irregular, Missed or Very Painful Periods</h3>
                                    </div>
                                    <p class="sign-desc">Occasional cycle fluctuations can happen, but periods that are frequently irregular or painful enough to disrupt your daily routine can point to Polycystic Ovary Syndrome (PCOS), thyroid disorders, uterine fibroids, or endometriosis.</p>
                                </div>

                                <div class="sign-card">
                                    <div class="sign-header">
                                        <div class="sign-icon"><i class="fas fa-tint"></i></div>
                                        <h3 class="sign-title">Heavy Bleeding (Menorrhagia)</h3>
                                    </div>
                                    <p class="sign-desc">Changing sanitary pads every hour or two, passing large blood clots, or bleeding for more than seven days is not normal. Heavy bleeding can quickly lead to severe anaemia, chronic fatigue, and weakness.</p>
                                </div>

                                <div class="sign-card">
                                    <div class="sign-header">
                                        <div class="sign-icon"><i class="fas fa-procedures"></i></div>
                                        <h3 class="sign-title">Pelvic or Lower Abdominal Pain</h3>
                                    </div>
                                    <p class="sign-desc">Ongoing or recurrent pelvic discomfort can stem from ovarian cysts, pelvic inflammatory disease (PID), urinary infections, or endometriosis. Early medical diagnosis makes treatment significantly simpler.</p>
                                </div>

                                <div class="sign-card">
                                    <div class="sign-header">
                                        <div class="sign-icon"><i class="fas fa-bacteria"></i></div>
                                        <h3 class="sign-title">Unusual Discharge, Itching or Burning</h3>
                                    </div>
                                    <p class="sign-desc">Changes in color, foul odor, thick consistency, or burning discomfort while passing urine can signal a bacterial or yeast infection that is easy to treat when diagnosed promptly.</p>
                                </div>

                                <div class="sign-card">
                                    <div class="sign-header">
                                        <div class="sign-icon"><i class="fas fa-baby-carriage"></i></div>
                                        <h3 class="sign-title">Difficulty Getting Pregnant</h3>
                                    </div>
                                    <p class="sign-desc">If you are under 35 and have not conceived after a year of unprotected intercourse (or after six months if over 35), a fertility evaluation helps identify underlying factors and map out the right next steps.</p>
                                </div>

                                <div class="sign-card">
                                    <div class="sign-header">
                                        <div class="sign-icon"><i class="fas fa-heartbeat"></i></div>
                                        <h3 class="sign-title">Pregnancy, or Planning One</h3>
                                    </div>
                                    <p class="sign-desc">From pre-conception health counselling and folic acid supplementation to comprehensive antenatal check-ups and ultrasound monitoring, good care early on protects both mother and baby.</p>
                                </div>

                                <div class="sign-card">
                                    <div class="sign-header">
                                        <div class="sign-icon"><i class="fas fa-sun"></i></div>
                                        <h3 class="sign-title">Menopause Symptoms</h3>
                                    </div>
                                    <p class="sign-desc">Hot flushes, night sweats, sleep disturbances, mood swings, and vaginal dryness can take a heavy toll on quality of life. You don't have to simply "bear with it"—safe, evidence-based therapies are readily available.</p>
                                </div>

                                <div class="sign-card urgent">
                                    <div class="sign-header">
                                        <div class="sign-icon"><i class="fas fa-exclamation-triangle"></i></div>
                                        <h3 class="sign-title" style="color: #be123c;">Bleeding After Menopause</h3>
                                    </div>
                                    <p class="sign-desc">Any spotting or vaginal bleeding that occurs after menopause is not normal and should always be checked by a gynaecologist immediately to rule out serious endometrial conditions.</p>
                                </div>
                            </div>
                        </section>

