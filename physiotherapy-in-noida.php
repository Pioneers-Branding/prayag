                                        commutes</span></li>
                                <li class="d-flex align-items-start gap-2 mb-2"><i
                                        class="fas fa-check-circle text-success mt-1"></i><span><strong>Physical
                                            inactivity</strong>, which weakens the core and back-supporting
                                        muscles</span></li>
                                <li class="d-flex align-items-start gap-2 mb-2"><i
                                        class="fas fa-check-circle text-success mt-1"></i><span><strong>Disc-related
