                        <!-- Section: Understanding Physiotherapy -->
                        <section id="understanding-physiotherapy" class="article-section">
                            <h2>Understanding Physiotherapy and Its Role in Physical Rehabilitation</h2>
                            <p>
                                Physiotherapy is a healthcare discipline that helps people restore, maintain, and
                                improve movement and physical function. It uses guided exercise, hands-on techniques,
                                education, and functional training to help the body recover from injury, illness,
                                surgery, or long-term strain.
                            </p>
                            <p>
                                Rehabilitation is the broader goal: helping a person return to the activities that
                                matter to them, whether that is climbing stairs without pain, returning to sport, or
                                managing household tasks independently. Physiotherapy sits at the centre of this
                                process. It works alongside medical treatment and, where needed, surgical care. Unlike
                                approaches that focus only on short-term relief, physiotherapy aims to build strength,
                                flexibility, and body awareness so that problems are less likely to return.
                            </p>
                        </section>

