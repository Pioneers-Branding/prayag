                        <section id="frequently-asked-questions" class="article-section">
                            <h2>Frequently Asked Questions</h2>
                            <div class="faq-accordion-box">
                                <div class="faq-item">
                                    <div class="faq-question" onclick="toggleFaq(this)">
                                        <span>1. What is the difference between a neurologist and a neurosurgeon?</span>
                                        <i class="fas fa-chevron-down"></i>
                                    </div>
                                    <div class="faq-answer">
                                        A neurologist treats brain, spine and nerve problems with medicines and
                                        non-surgical care. A neurosurgeon treats these problems with surgery when it is
                                        needed.
                                    </div>
                                </div>

                                <div class="faq-item">
                                    <div class="faq-question" onclick="toggleFaq(this)">
                                        <span>2. Which conditions are treated by a neurologist?</span>
                                        <i class="fas fa-chevron-down"></i>
                                    </div>
                                    <div class="faq-answer">
                                        A neurologist treats migraine, epilepsy, stroke, Parkinson's disease, dementia,
                                        vertigo, nerve pain, neuropathy and multiple sclerosis.
                                    </div>
                                </div>

                                <div class="faq-item">
                                    <div class="faq-question" onclick="toggleFaq(this)">
                                        <span>3. When should someone consult a neurosurgeon?</span>
                                        <i class="fas fa-chevron-down"></i>
                                    </div>
                                    <div class="faq-answer">
                                        You should consult a neurosurgeon if you have a brain or spine tumour, serious
                                        head or spine injury, brain bleed, or a slip disc that causes severe pain,
                                        weakness or loss of bladder control and does not improve with other treatment.
                                    </div>
                                </div>

                                <div class="faq-item">
                                    <div class="faq-question" onclick="toggleFaq(this)">
                                        <span>4. What is neuro surgery?</span>
                                        <i class="fas fa-chevron-down"></i>
                                    </div>
                                    <div class="faq-answer">
                                        Neuro surgery is surgery on the brain, spinal cord or nerves. It is used to remove
                                        tumours, stop bleeding, relieve pressure on nerves and repair injuries.
                                    </div>
                                </div>

                                <div class="faq-item">
                                    <div class="faq-question" onclick="toggleFaq(this)">
                                        <span>5. Can brain and spine conditions be treated without surgery?</span>
                                        <i class="fas fa-chevron-down"></i>
                                    </div>
                                    <div class="faq-answer">
                                        Yes. Many conditions like migraine, epilepsy, mild slip disc, neck pain and back
                                        pain are treated with medicines, physiotherapy, injections and lifestyle changes.
                                        Surgery is advised only when needed.
                                    </div>
                                </div>

                                <div class="faq-item">
                                    <div class="faq-question" onclick="toggleFaq(this)">
                                        <span>6. What tests are used to diagnose neurological disorders?</span>
                                        <i class="fas fa-chevron-down"></i>
                                    </div>
                                    <div class="faq-answer">
                                        Common tests include CT scan, MRI, EEG, EMG, nerve conduction study, blood tests,
                                        spine X-ray and blood flow studies like angiography or Doppler.
                                    </div>
                                </div>

                                <div class="faq-item">
                                    <div class="faq-question" onclick="toggleFaq(this)">
                                        <span>7. What is the difference between a CT scan and an MRI for brain
                                            evaluation?</span>
                                        <i class="fas fa-chevron-down"></i>
                                    </div>
                                    <div class="faq-answer">
                                        A CT scan uses X-rays, takes only a few minutes, and is best for emergencies like
                                        bleeding, stroke or head injury. An MRI uses a strong magnet and no radiation. It
                                        takes longer but gives more detailed pictures of the brain, spinal cord and
                                        nerves, making it better for tumours, nerve problems and disc issues.
                                    </div>
                                </div>
