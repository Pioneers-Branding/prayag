                        <!-- Section: When Neurosurgery -->
                        <section id="when-neurosurgery" class="article-section">
                            <h2>When Is Neurosurgery Required for Brain and Spine Conditions?</h2>
                            <p>Surgery is not the first choice for most patients. A neurosurgeon may advise surgery
                                when:</p>
                            <ul class="hospital-tips-list mb-3 list-unstyled">
                                <li class="d-flex align-items-start gap-2 mb-2"><i
                                        class="fas fa-check-circle text-success mt-1"></i><span>There is a tumour in the
                                        brain or spine</span></li>
                                <li class="d-flex align-items-start gap-2 mb-2"><i
                                        class="fas fa-check-circle text-success mt-1"></i><span>There is bleeding in the
                                        brain that is pressing on brain tissue</span></li>
                                <li class="d-flex align-items-start gap-2 mb-2"><i
                                        class="fas fa-check-circle text-success mt-1"></i><span>A serious head or spine
                                        injury needs urgent repair</span></li>
                                <li class="d-flex align-items-start gap-2 mb-2"><i
                                        class="fas fa-check-circle text-success mt-1"></i><span>A slip disc causes severe
                                        pain or weakness that does not improve with medicines and physiotherapy for
                                        several weeks</span></li>
                                <li class="d-flex align-items-start gap-2 mb-2"><i
                                        class="fas fa-check-circle text-success mt-1"></i><span>There is loss of bladder
                                        or bowel control due to nerve compression</span></li>
                                <li class="d-flex align-items-start gap-2 mb-2"><i
                                        class="fas fa-check-circle text-success mt-1"></i><span>Spinal cord compression is
                                        causing weakness in the arms or legs</span></li>
                            </ul>
                            <p>
                                Modern spine surgery, including minimally invasive and microscopic procedures, helps many
                                patients get back to normal life faster. Experienced <strong>neuro surgeons in Greater
                                    Noida</strong> and Noida carefully weigh the risks and benefits before suggesting any
                                operation.
                            </p>
                        </section>

                        <!-- Section: Neuro-Critical Care -->
                        <section id="neuro-critical-care" class="article-section">
                            <h2>What Is Neuro-Critical Care and When Is It Required?</h2>
                            <p>
                                Neuro-critical care is special intensive care for patients with serious brain or spine
                                problems. These patients need close watch 24 hours a day.
                            </p>
                            <p>It may be required for:</p>
                            <ul class="hospital-tips-list mb-3 list-unstyled">
                                <li class="d-flex align-items-start gap-2 mb-2"><i
                                        class="fas fa-check-circle text-success mt-1"></i><span>Major stroke or brain
                                        bleed</span></li>
                                <li class="d-flex align-items-start gap-2 mb-2"><i
                                        class="fas fa-check-circle text-success mt-1"></i><span>Severe head
                                        injury</span></li>
                                <li class="d-flex align-items-start gap-2 mb-2"><i
                                        class="fas fa-check-circle text-success mt-1"></i><span>Patients recovering after
                                        brain or spine surgery</span></li>
                                <li class="d-flex align-items-start gap-2 mb-2"><i
                                        class="fas fa-check-circle text-success mt-1"></i><span>Continuous seizures that do
                                        not stop</span></li>
                                <li class="d-flex align-items-start gap-2 mb-2"><i
                                        class="fas fa-check-circle text-success mt-1"></i><span>Brain infections such as
                                        meningitis or encephalitis</span></li>
                            </ul>
                            <p>
                                In the <a href="critical-care">ICU</a>, doctors and nurses check brain function,
                                breathing, blood pressure and oxygen levels round the clock. Quick action in these early
                                hours can save lives and reduce long-term disability.
                            </p>
                        </section>

