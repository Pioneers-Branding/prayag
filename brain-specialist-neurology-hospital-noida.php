                                            href="physiotherapy">Physiotherapy</a> to improve walking, balance and muscle
                                        strength</span></li>
                                <li class="d-flex align-items-start gap-2 mb-2"><i
                                        class="fas fa-check-circle text-success mt-1"></i><span>Occupational therapy to
