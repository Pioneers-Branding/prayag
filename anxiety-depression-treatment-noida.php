                        <section id="frequently-asked-questions" class="article-section">
                            <h2>Frequently Asked Questions</h2>
                            <div class="faq-accordion-box">
                                <div class="faq-item">
                                    <div class="faq-question" onclick="toggleFaq(this)">
                                        <span>How do I know if my worry is everyday stress or clinical anxiety?</span>
                                        <i class="fas fa-chevron-down"></i>
                                    </div>
                                    <div class="faq-answer">
                                        Everyday stress is temporary and usually tied to an identifiable external situation (such as an exam, interview, or deadline). Clinical anxiety persists continuously for two weeks or more, feels beyond your voluntary control, and impairs your sleep, work, or relationships. If physical symptoms like unexplained palpitations, trembling, sweating, or breathlessness accompany your worry, it is advisable to seek medical evaluation.
                                    </div>
                                </div>

                                <div class="faq-item">
                                    <div class="faq-question" onclick="toggleFaq(this)">
                                        <span>Are psychiatric medicines for anxiety and depression habit-forming?</span>
                                        <i class="fas fa-chevron-down"></i>
                                    </div>
                                    <div class="faq-answer">
                                        No. Modern antidepressants (such as SSRIs and SNRIs) and mood regulators prescribed by qualified psychiatrists are strictly non-habit forming. They work gently by rebalancing serotonin and other neurotransmitters in the brain. They are prescribed under controlled medical tapering schedules and should never be stopped abruptly without consulting your treating doctor.
                                    </div>
                                </div>

                                <div class="faq-item">
                                    <div class="faq-question" onclick="toggleFaq(this)">
                                        <span>Why are blood tests like thyroid or Vitamin B12 advised for low mood?</span>
                                        <i class="fas fa-chevron-down"></i>
                                    </div>
                                    <div class="faq-answer">
                                        Physical endocrine and nutritional disorders can directly mimic psychiatric conditions. For instance, an underactive thyroid gland (hypothyroidism), severe Vitamin B12 deficiency, or profound Vitamin D deficiency can produce chronic fatigue, low mood, memory lapses, and panic-like states. Blood tests rule out or address these reversible physical causes before or alongside psychological therapy.
                                    </div>
                                </div>

                                <div class="faq-item">
                                    <div class="faq-question" onclick="toggleFaq(this)">
                                        <span>What should I bring to my first mental health consultation at Prayag Hospital?</span>
                                        <i class="fas fa-chevron-down"></i>
                                    </div>
                                    <div class="faq-answer">
                                        We recommend bringing a list of all current prescription and non-prescription medicines you consume, copies of earlier routine blood tests or ECG reports, and brief notes on your sleep and symptom timeline. Bringing along an empathetic family member or close friend is also warmly encouraged.
                                    </div>
                                </div>

