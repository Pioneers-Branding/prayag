                        <section id="signs-enlarged-prostate" class="article-section">
                            <h2>Signs of an Enlarged Prostate</h2>
                            <p>
                                Frequent nighttime visits to the bathroom rarely happen alone. Men with BPH frequently notice several of the following lower urinary tract symptoms (LUTS):
                            </p>

                            <div class="symptoms-grid">
                                <div class="symptom-card">
                                    <div class="symptom-icon"><i class="fas fa-tint-slash"></i></div>
                                    <div class="symptom-text">
                                        <h4>Weak or Slow Urine Stream</h4>
                                        <p>The flow of urine is noticeably weaker and takes longer to finish.</p>
                                    </div>
                                </div>

                                <div class="symptom-card">
                                    <div class="symptom-icon"><i class="fas fa-hourglass-start"></i></div>
                                    <div class="symptom-text">
                                        <h4>Hesitancy &amp; Straining</h4>
                                        <p>Difficulty starting the stream, or needing to push and strain the abdomen.</p>
                                    </div>
                                </div>

                                <div class="symptom-card">
                                    <div class="symptom-icon"><i class="fas fa-stream"></i></div>
                                    <div class="symptom-text">
                                        <h4>Intermittent Flow</h4>
                                        <p>A urine stream that starts, stops, and restarts several times.</p>
                                    </div>
                                </div>

                                <div class="symptom-card">
                                    <div class="symptom-icon"><i class="fas fa-tint"></i></div>
                                    <div class="symptom-text">
                                        <h4>Terminal Dribbling</h4>
                                        <p>Continued dribbling of urine at the end of passing urine.</p>
                                    </div>
                                </div>

                                <div class="symptom-card">
                                    <div class="symptom-icon"><i class="fas fa-battery-half"></i></div>
                                    <div class="symptom-text">
                                        <h4>Incomplete Bladder Emptying</h4>
                                        <p>A persistent sensation that your bladder is never completely empty.</p>
                                    </div>
                                </div>

                                <div class="symptom-card">
                                    <div class="symptom-icon"><i class="fas fa-bolt"></i></div>
                                    <div class="symptom-text">
                                        <h4>Sudden Urinary Urgency</h4>
                                        <p>A sudden, intense urge to urinate that is difficult to postpone.</p>
                                    </div>
                                </div>
                            </div>
                        </section>

                        <!-- Section 4: Other Reasons -->
                        <section id="other-causes" class="article-section">
                            <h2>Other Reasons You May Wake Up to Urinate</h2>
                            <p>
                                While an enlarged prostate is the most frequent cause in men over 45, nocturia can also be triggered or exacerbated by several other medical factors:
                            </p>

                            <div class="causes-pill-grid">
                                <div class="cause-pill-item"><i class="fas fa-coffee"></i> High evening intake of fluids, tea, coffee or alcohol</div>
                                <div class="cause-pill-item"><i class="fas fa-vial"></i> Poorly controlled diabetes or high blood sugar</div>
                                <div class="cause-pill-item"><i class="fas fa-bacteria"></i> Urinary tract infection (UTI) or cystitis</div>
                                <div class="cause-pill-item"><i class="fas fa-heartbeat"></i> Overactive bladder (OAB) syndrome</div>
                                <div class="cause-pill-item"><i class="fas fa-pills"></i> Diuretic medications (water pills) taken late in the day</div>
                                <div class="cause-pill-item"><i class="fas fa-lungs"></i> Obstructive sleep apnoea (disrupted breathing)</div>
                                <div class="cause-pill-item"><i class="fas fa-procedures"></i> Congestive heart failure or kidney conditions (with ankle swelling)</div>
                            </div>

                            <p>
                                This is precisely why a comprehensive medical check-up matters: identifying and addressing the exact underlying cause guarantees the best possible outcome.
                            </p>
                        </section>

