                        <!-- Section 1: Is Waking Up Normal -->
                        <section id="is-nocturia-normal" class="article-section">
                            <h2>Is Waking Up at Night to Urinate Normal?</h2>
                            <p>
                                Waking up once during the night to urinate can be normal, especially as you age. However, doctors call frequent night-time urination <strong>nocturia</strong>, and it is definitely worth discussing with a doctor if you regularly wake up <strong>twice or more each night</strong> to pass urine.
                            </p>
                            <p>
                                Broken sleep is far from a minor inconvenience. Over time, chronic sleep fragmentation leads to daytime fatigue, brain fog, irritability, decreased productivity, and a significantly higher risk of nighttime falls and fractures, especially in older men.
                            </p>
                        </section>

                        <!-- Section 2: How the Prostate Causes Nocturia -->
                        <section id="prostate-and-night-urination" class="article-section">
                            <h2>How the Prostate Can Cause Night-Time Urination</h2>
                            <p>
                                The prostate is a walnut-sized gland that sits directly below the bladder and surrounds the urethra (the tube that carries urine out of the body). In many men, the prostate gradually increases in size as hormone levels change with age. This non-cancerous condition is known as <strong>Benign Prostatic Hyperplasia (BPH)</strong>, or an enlarged prostate.
                            </p>
                            <p>
                                As the prostate enlarges, it pinches the urethra and exerts pressure on the base of the bladder. Consequently, the bladder muscles must work harder to pump urine and cannot empty completely. Because residual urine remains trapped, the bladder fills back up quickly, triggering frequent urges to urinate throughout the night.
                            </p>
                            <div style="background: #f0fdf4; border-left: 4px solid #16a34a; border-radius: 10px; padding: 16px 20px; margin: 15px 0 25px;">
                                <p style="margin: 0; color: #166534; font-weight: 500;">
                                    <i class="fas fa-check-circle me-1"></i> <strong>Good to Know:</strong> BPH is exceptionally common—over 50% of men in their 60s and up to 90% of men over 70 experience some degree of prostate enlargement. Crucially, <strong>BPH is not cancer, and it does not turn into cancer</strong>.
                                </p>
                            </div>
                        </section>

