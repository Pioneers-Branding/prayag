                        <!-- Section 7: Treatment Options -->
                        <section id="treatment-options" class="article-section">
                            <h2>Treatment Options: You Don't Have to Live With It</h2>
                            <p>
                                The great news is that BPH and nocturia are highly treatable conditions. Treatment is customised based on how much the symptoms affect your day-to-day comfort:
                            </p>

                            <div class="treatment-options-container">
                                <div class="treatment-item-card">
                                    <div class="treatment-item-header">
                                        <div class="treatment-item-icon"><i class="fas fa-walking"></i></div>
                                        <h4>1. Targeted Lifestyle Modifications</h4>
                                    </div>
                                    <p>For mild symptoms, restricting fluid intake 2 hours before bedtime, avoiding caffeine and alcohol in the evenings, doing pelvic floor exercises, and practicing "double voiding" (emptying bladder twice before sleep) can dramatically cut night trips.</p>
                                </div>

                                <div class="treatment-item-card">
                                    <div class="treatment-item-header">
                                        <div class="treatment-item-icon"><i class="fas fa-pills"></i></div>
                                        <h4>2. Medical Therapy</h4>
                                    </div>
                                    <p>Modern medications such as Alpha-blockers (which relax the smooth muscles of the prostate and bladder neck) and 5-Alpha Reductase Inhibitors (which gradually shrink the enlarged prostate gland) provide rapid symptom relief and restore smooth urine flow.</p>
                                </div>

                                <div class="treatment-item-card">
                                    <div class="treatment-item-header">
                                        <div class="treatment-item-icon"><i class="fas fa-laser-pointer"></i></div>
                                        <h4>3. Advanced Minimally Invasive Surgery</h4>
                                    </div>
                                    <p>If medications do not provide adequate relief or the obstruction is severe, advanced endoscopic procedures such as <strong>Transurethral Resection of the Prostate (TURP)</strong> or <strong>Holmium/Thulium Laser Prostate Enucleation (HoLEP)</strong> effectively clear the blockage with minimal blood loss, minimal hospital stay, and quick recovery.</p>
                                </div>
                            </div>
                        </section>

