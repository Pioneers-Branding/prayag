                        <section id="pre-anesthetic-check-up" class="article-section">
                            <h2>What Is a Pre-Anesthetic Check-Up and Why Is It Necessary?</h2>
                            <p>
                                A pre-anesthetic check-up (PAC) is a health review done a few days or hours before
                                surgery. It helps the medical anesthesiologist spot any risk early and plan safe
                                anesthesia. Skipping this step can lead to surprises in the operation theatre, so it is a
                                standard part of care at every good surgical hospital in Noida.
                            </p>
                            <div class="inline-figure">
                                <img loading="lazy" decoding="async"
