                            <h3 class="h5 fw-bold mt-4">Medical History and Physical Evaluation</h3>
                            <p>
                                The doctor asks about conditions like diabetes, high blood pressure, heart disease,
                                asthma, thyroid problems, kidney or liver disease, and sleep apnea. They also ask about
                                smoking, alcohol use, blood thinners and herbal supplements. A physical check of the
                                heart, lungs, airway, mouth opening and neck movement helps them judge how easy it will
                                be to manage breathing during surgery.
                            </p>

                            <h3 class="h5 fw-bold mt-4">Diagnostic Investigations Before Anesthesia</h3>
                            <p>
                                Based on age and health, the doctor may ask for blood tests (CBC, sugar, kidney and liver
                                function, clotting profile), ECG, chest X-ray, and in some cases echocardiography or lung
                                function tests. These tests show how well the body can handle anesthesia and surgery.
                            </p>

                            <h3 class="h5 fw-bold mt-4">Fasting Instructions and Pre-Surgical Preparation</h3>
                            <p>
                                Patients are usually asked not to eat solid food for about 6 to 8 hours before general
                                anesthesia, though clear fluids like water may be allowed until around 2 hours before,
                                as advised by the doctor. Fasting keeps the stomach empty, which lowers the risk of food
                                or acid going into the lungs. The team also tells the patient which regular medicines to
                                continue or stop on the day of surgery.
                            </p>

                            <h3 class="h5 fw-bold mt-4">Individualized Anesthesia Risk Assessment</h3>
                            <p>
                                After all checks, the anesthesiologist grades the patient's overall fitness, often using
                                the ASA (American Society of Anesthesiologists) scale. This helps decide the safest
                                anesthesia plan, whether extra monitoring is needed, and whether an ICU bed should be
                                kept ready after surgery.
                            </p>
