                        <!-- Section: How it spreads -->
                        <section id="how-flu-spreads" class="article-section">
                            <h2>How Viral Flu Spreads in Noida Homes and Offices</h2>
                            <p>
                                The influenza virus travels in microscopic respiratory droplets expelled into the air whenever an infected person coughs, sneezes, or talks. These droplets can directly land in the mouths or noses of people nearby or settle on everyday touchpoints.
                            </p>
                            <p>
                                The virus can survive for hours on common high-contact surfaces—door handles, lift buttons, metro railings, shared phones, and office keyboards.
                            </p>
                            <p>
                                Crucially, an infected individual can pass the virus on <strong>one full day before any symptoms appear</strong> and for roughly a week after falling sick. That is why a single sick child in school so often results in an entire household catching fever, and why pushing yourself to go to work "with just a little fever" can inadvertently leave an entire team sidelined.
                            </p>
                        </section>

