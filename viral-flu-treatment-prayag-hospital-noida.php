                                        <i class="fas fa-chevron-down"></i>
                                    </div>
                                    <div class="faq-answer">
                                        An infected individual can transmit influenza starting 24 hours before their symptoms appear and for approximately 5 to 7 days after falling sick. Young children and people with compromised immunity can remain contagious for even longer.
                                    </div>
                                </div>

                                <div class="faq-item">
                                    <div class="faq-question" onclick="toggleFaq(this)">
