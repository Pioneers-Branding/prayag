                                <div class="faq-item">
                                    <div class="faq-question" onclick="toggleFaq(this)">
                                        <span>What is the difference between a common cold and viral flu?</span>
                                        <i class="fas fa-chevron-down"></i>
                                    </div>
                                    <div class="faq-answer">
                                        A common cold creeps in slowly with sneezing, a runny nose, and mild malaise, rarely causing high fever. Viral flu hits suddenly within hours, bringing high fever (100°F–103°F+), severe body ache, intense headache, dry cough, and profound fatigue that leaves the patient completely bedridden.
                                    </div>
                                </div>

                                <div class="faq-item">
                                    <div class="faq-question" onclick="toggleFaq(this)">
                                        <span>Can antibiotics cure viral flu?</span>
                                        <i class="fas fa-chevron-down"></i>
                                    </div>
                                    <div class="faq-answer">
                                        No. Antibiotics are only effective against bacteria; they have zero therapeutic impact on the influenza virus. Unsupervised antibiotic consumption causes digestive side effects and antimicrobial resistance. They are prescribed solely when a physician confirms a secondary bacterial infection on top of the viral illness.
                                    </div>
                                </div>

                                <div class="faq-item">
                                    <div class="faq-question" onclick="toggleFaq(this)">
                                        <span>When should someone with flu visit a hospital in Noida?</span>
                                        <i class="fas fa-chevron-down"></i>
                                    </div>
                                    <div class="faq-answer">
                                        Visit the hospital if fever stays high beyond 3 days, if there is breathlessness or chest tightness, if fever rebounds after initially subsiding, if there is mental confusion or inability to stay hydrated, or if a child shows rapid breathing, poor feeding, or bluish lips.
                                    </div>
                                </div>

                                <div class="faq-item">
                                    <div class="faq-question" onclick="toggleFaq(this)">
