                        <!-- Section: How to Protect -->
                        <section id="how-to-protect" class="article-section">
                            <h2>How to Protect Yourself and Your Family</h2>
                            <p>
                                You cannot change the air outside, but you can significantly reduce how much of it you breathe.
                            </p>

                            <div class="prevention-steps-grid">
                                <div class="step-item">
                                    <div class="step-icon">1</div>
                                    <div>
                                        <h5>Check the AQI Every Morning</h5>
                                        <p>Use the SAMEER app or CPCB website. Plan outdoor activity around it.</p>
                                    </div>
                                </div>
                                <div class="step-item">
                                    <div class="step-icon">2</div>
                                    <div>
                                        <h5>Shift Your Walk or Workout</h5>
                                        <p>Pollution is usually highest early morning and late evening in winter. On Poor or worse days, exercise indoors.</p>
                                    </div>
                                </div>
                                <div class="step-item">
                                    <div class="step-icon">3</div>
                                    <div>
                                        <h5>Wear the Right Mask</h5>
                                        <p>A well-fitted N95 or N99 mask filters fine particles. Cloth and surgical masks offer little protection against PM2.5.</p>
                                    </div>
                                </div>
                                <div class="step-item">
                                    <div class="step-icon">4</div>
                                    <div>
                                        <h5>Keep Indoor Air Cleaner</h5>
                                        <p>Keep windows closed on high-AQI days and ventilate briefly in the afternoon when levels dip. An air purifier with a HEPA filter helps in bedrooms. Avoid incense, mosquito coils and indoor smoking.</p>
                                    </div>
                                </div>
                                <div class="step-item">
                                    <div class="step-icon">5</div>
                                    <div>
                                        <h5>Stay Hydrated and Eat Well</h5>
                                        <p>Water keeps airways moist. Fresh fruits and vegetables rich in vitamin C and antioxidants support your body's natural defences.</p>
                                    </div>
                                </div>
                                <div class="step-item">
                                    <div class="step-icon">6</div>
                                    <div>
                                        <h5>Do Not Stop Prescribed Medicines</h5>
                                        <p>If you have asthma, COPD or heart disease, keep your inhalers and medicines handy and take them as advised. Speak to your doctor before winter about whether your plan needs adjusting.</p>
                                    </div>
                                </div>
                                <div class="step-item">
                                    <div class="step-icon">7</div>
                                    <div>
                                        <h5>Get Vaccinated</h5>
                                        <p>Ask your doctor about flu and pneumonia vaccines, especially for children, older adults and people with chronic illness.</p>
                                    </div>
                                </div>
                                <div class="step-item">
                                    <div class="step-icon">8</div>
                                    <div>
                                        <h5>Rinse and Soothe</h5>
                                        <p>Washing your face and eyes after coming indoors and steam inhalation can ease irritation.</p>
                                    </div>
                                </div>
                                <div class="step-item">
                                    <div class="step-icon">9</div>
                                    <div>
                                        <h5>Celebrate Diwali Responsibly</h5>
                                        <p>Firecracker smoke sharply worsens the air for days afterwards. Keep children and elderly family members indoors during the peak.</p>
                                    </div>
                                </div>
                            </div>
                        </section>

