                        <!-- Section: How Pollution Affects the Body -->
                        <section id="how-pollution-affects-body" class="article-section">
                            <h2>How Air Pollution Affects Your Body</h2>
                            <p>
                                The most harmful part of NCR's winter air is fine particulate matter, called <strong>PM2.5</strong>. These particles are about 30 times thinner than a human hair. They travel deep into the lungs and some pass into the bloodstream, which is why pollution affects far more than breathing.
                            </p>

                            <div class="symptoms-grid">
                                <div class="symptom-card">
                                    <div class="symptom-icon"><i class="fas fa-lungs"></i></div>
                                    <div class="symptom-info">
                                        <h4>Lungs and Airways</h4>
                                        <p>Polluted air inflames the airways. This shows up as a dry cough, throat irritation, wheezing and breathlessness. It also makes people more prone to bronchitis and pneumonia, and it triggers attacks in people with asthma or COPD.</p>
                                    </div>
                                </div>
                                <div class="symptom-card">
                                    <div class="symptom-icon"><i class="fas fa-heartbeat"></i></div>
                                    <div class="symptom-info">
                                        <h4>Heart and Blood Pressure</h4>
                                        <p>Fine particles cause inflammation in blood vessels and can raise blood pressure. During high-pollution periods, doctors see more cases of chest pain, irregular heartbeat and heart attacks, especially in people who already have heart disease.</p>
                                    </div>
                                </div>
                                <div class="symptom-card">
                                    <div class="symptom-icon"><i class="fas fa-eye"></i></div>
                                    <div class="symptom-info">
                                        <h4>Eyes, Nose and Skin</h4>
                                        <p>Burning, watery and red eyes, a blocked or runny nose, sneezing, and dry, itchy skin are common through November and December.</p>
                                    </div>
                                </div>
                                <div class="symptom-card">
                                    <div class="symptom-icon"><i class="fas fa-brain"></i></div>
                                    <div class="symptom-info">
                                        <h4>Brain and Overall Wellbeing</h4>
                                        <p>Many people report headaches, fatigue, poor sleep and difficulty concentrating on high-AQI days. Long-term exposure is also linked with a higher risk of stroke.</p>
                                    </div>
                                </div>
                            </div>
                        </section>

