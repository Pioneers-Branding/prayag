                        <!-- Section: What Is an Ultrasound Test? -->
                        <section id="what-is-ultrasound" class="article-section">
                            <h2>What Is an Ultrasound Test?</h2>
                            <p>
                                An <strong>ultrasound test</strong>, also called <strong>sonography</strong>, uses high-frequency sound waves to create live, detailed images of the organs, tissues and blood vessels inside your body. A small handheld device called a transducer is moved over the skin, sending sound waves into the body and capturing the echoes that bounce back. These echoes are converted into live images on a high-resolution monitor.
                            </p>
                            <p>
                                Because it uses sound waves rather than radiation, an ultrasound is considered very safe. This is exactly why it is the preferred method for monitoring pregnancy and for examining soft tissues that an X-ray cannot show clearly. Most scans are quick, cause no discomfort and require little to no downtime.
                            </p>
                        </section>

