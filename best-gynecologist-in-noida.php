                        <!-- Section: What Does a Gynecologist Do? -->
                        <section id="what-does-a-gynecologist-do" class="article-section">
                            <h2>What Does a Gynecologist Do?</h2>
                            <p>
                                A gynecologist is a medical doctor who specialises in the female reproductive system, including the uterus, ovaries, cervix, fallopian tubes and related organs. Many gynecologists are also obstetricians (OB-GYNs), meaning they care for women through conception, pregnancy, labour and childbirth.
                            </p>
                            <p>
                                A gynecologist can help with menstrual health, hormonal concerns, infections, contraception, fertility, pregnancy and screening for critical conditions such as cervical and breast cancer. Building a relationship with a trusted gynecologist means you have a professional who understands your history and can guide you through changes in your body over the years.
                            </p>
                        </section>

                        <!-- Section: When Should You See a Gynecologist? -->
                        <section id="when-should-you-see-one" class="article-section">
                            <h2>When Should You See a Gynecologist?</h2>
                            <p>
                                There is no single right time. Different situations, symptoms and life stages call for a visit. Here are the most important reasons to consult a specialist:
                            </p>

                            <div class="stages-grid">
                                <!-- Item 1 -->
                                <div class="stage-card">
                                    <div class="stage-icon">
                                        <i class="fas fa-child"></i>
                                    </div>
                                    <h4>1. First Visit in Adolescence or Early Adulthood</h4>
                                    <p>Health experts generally suggest that a young woman have her first gynecological consultation in her teens or early twenties, or earlier if she has concerns. This first visit is often about guidance, lifestyle counselling and reassurance rather than physical examination, helping set the foundation for lifelong care.</p>
                                </div>

                                <!-- Item 2 -->
                                <div class="stage-card">
                                    <div class="stage-icon">
                                        <i class="fas fa-calendar-times"></i>
                                    </div>
                                    <h4>2. Irregular, Painful or Heavy Periods</h4>
                                    <p>Occasional changes in your cycle can be normal, but periods that are consistently irregular, extremely painful (dysmenorrhea), unusually heavy or that stop without explanation should be checked. These can point to hormonal imbalances, fibroids, endometriosis or other conditions that respond well to early treatment.</p>
                                </div>

                                <!-- Item 3 -->
                                <div class="stage-card">
                                    <div class="stage-icon">
                                        <i class="fas fa-dna"></i>
                                    </div>
                                    <h4>3. Symptoms of PCOS</h4>
                                    <p>Polycystic ovary syndrome (PCOS) is one of the most common hormonal disorders in women of reproductive age. Signs may include irregular periods, weight gain, acne, excess facial/body hair and difficulty conceiving. PCOS cannot be cured, but seeking <strong>PCOS treatment in Noida</strong> early can help you manage the condition and lower long-term risks such as diabetes.</p>
                                </div>

                                <!-- Item 4 -->
                                <div class="stage-card">
                                    <div class="stage-icon">
                                        <i class="fas fa-baby-carriage"></i>
                                    </div>
                                    <h4>4. Planning or Confirming a Pregnancy</h4>
                                    <p>If you are planning to conceive, a pre-pregnancy consultation helps prepare your body and identify any risks in advance. Once pregnant, regular <strong>pregnancy care in Noida</strong> is essential to monitor both mother and baby, track fetal growth, screen for complications and support a safe delivery.</p>
                                </div>

                                <!-- Item 5 -->
                                <div class="stage-card">
                                    <div class="stage-icon">
                                        <i class="fas fa-shield-virus"></i>
                                    </div>
                                    <h4>5. Unusual Discharge, Pain or Discomfort</h4>
                                    <p>Persistent itching, unusual vaginal discharge, a foul odour, burning during urination or pelvic pain may signal an infection or another condition. These symptoms are common, treatable and nothing to feel embarrassed about, so it is best to get them assessed rather than ignored.</p>
                                </div>

                                <!-- Item 6 -->
                                <div class="stage-card">
                                    <div class="stage-icon">
                                        <i class="fas fa-pills"></i>
                                    </div>
                                    <h4>6. Contraception and Family Planning</h4>
                                    <p>Whether you want to prevent pregnancy, space your children or understand your options, a gynecologist can help you choose a method—such as oral contraceptives, IUDs, or barrier methods—that suits your health and lifestyle safely.</p>
                                </div>

                                <!-- Item 7 -->
                                <div class="stage-card">
                                    <div class="stage-icon">
                                        <i class="fas fa-leaf"></i>
                                    </div>
                                    <h4>7. Menopause and Beyond</h4>
                                    <p>As women approach their forties and fifties, changing hormone levels can bring hot flushes, mood changes, irregular periods and other symptoms. A gynecologist can help manage this transition comfortably and monitor bone density and heart health, which need extra attention post-menopause.</p>
                                </div>

                                <!-- Item 8 -->
                                <div class="stage-card">
                                    <div class="stage-icon">
                                        <i class="fas fa-notes-medical"></i>
                                    </div>
                                    <h4>8. Routine Screenings and Check-ups</h4>
                                    <p>Even when you feel perfectly well, routine preventive care matters. Regular pelvic examinations, cervical cancer screening through a Pap smear and clinical breast examinations help detect problems early, often before symptoms appear.</p>
                                </div>
                            </div>

                            <!-- Statutory Compliance Box -->
                            <div class="compliance-callout">
                                <i class="fas fa-balance-scale callout-icon"></i>
                                <div>
                                    <h5>Statutory Medical & Diagnostic Compliance (PCPNDT Act)</h5>
                                    <p>Please note that under Indian law, specifically the <strong>PCPNDT Act</strong>, using any test or diagnostic procedure to determine the sex of an unborn baby is strictly prohibited. All ultrasound scans and tests during pregnancy at Prayag Hospital are carried out purely for medical, diagnostic, and fetal health monitoring purposes.</p>
                                </div>
                            </div>
                        </section>

