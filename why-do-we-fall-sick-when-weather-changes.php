                        <!-- Intro Lead -->
                        <div class="article-intro">
                            <p>
                                As the monsoon fades and cooler evenings set in, many households start sneezing, coughing and running a temperature. This time of year is one of the busiest for the OPD at <strong>Prayag Hospital, Sector 41, Noida</strong>, where our doctors see a sharp rise in fever, throat infections, stomach upsets and breathing problems between <strong>September and November</strong>.
                            </p>
                            <p>
                                Most seasonal illnesses are mild and get better with rest and simple care. Some, like dengue, need timely diagnosis and close monitoring. Here is what causes seasonal illness, what to watch for, and when a doctor's visit becomes important.
                            </p>
