                        <!-- Section 1: What Makes Us Sick -->
                        <section id="what-makes-us-sick" class="article-section">
                            <h2>What Makes Us Sick During Weather Change?</h2>
                            <p>
                                The change in weather doesn't cause illness directly. Rather, fluctuating meteorological conditions create an ideal environment for viruses, bacteria, and insect vectors to thrive and spread rapidly:
                            </p>

                            <div class="cause-grid">
                                <div class="cause-card">
                                    <div class="cause-card-header">
                                        <div class="cause-icon"><i class="fas fa-temperature-high"></i></div>
                                        <h3 class="cause-card-title">Temperature Swings</h3>
                                    </div>
                                    <p class="cause-card-desc">Warm sunny days followed by cool nights make it harder for the body's thermoregulatory and immune defenses to adjust smoothly.</p>
                                </div>

                                <div class="cause-card">
                                    <div class="cause-card-header">
                                        <div class="cause-icon"><i class="fas fa-tint"></i></div>
                                        <h3 class="cause-card-title">Leftover Rainwater</h3>
                                    </div>
                                    <p class="cause-card-desc">Stagnant water pools in air coolers, flower pots and construction sites breed mosquitoes that spread dengue, malaria and chikungunya.</p>
                                </div>

                                <div class="cause-card">
                                    <div class="cause-card-header">
                                        <div class="cause-icon"><i class="fas fa-door-closed"></i></div>
                                        <h3 class="cause-card-title">Closed Indoor Spaces</h3>
                                    </div>
                                    <p class="cause-card-desc">Cooler evenings bring people indoors with closed ventilation, where respiratory viruses pass easily from person to person.</p>
                                </div>

                                <div class="cause-card">
                                    <div class="cause-card-header">
                                        <div class="cause-icon"><i class="fas fa-smog"></i></div>
                                        <h3 class="cause-card-title">Rising Air Pollution</h3>
                                    </div>
                                    <p class="cause-card-desc">Falling temperature traps pollutants near ground level. Poor air quality irritates the respiratory tract and triggers severe asthma and allergy flare-ups.</p>
                                </div>

                                <div class="cause-card">
                                    <div class="cause-card-header">
                                        <div class="cause-icon"><i class="fas fa-utensils"></i></div>
                                        <h3 class="cause-card-title">Contaminated Food &amp; Water</h3>
                                    </div>
                                    <p class="cause-card-desc">Lingering post-monsoon humidity and water pipeline seepage raise the risk of waterborne bacterial infections like typhoid and acute gastroenteritis.</p>
                                </div>
                            </div>
                        </section>

                        <!-- Section 2: Common Seasonal Illnesses -->
                        <section id="common-illnesses" class="article-section">
                            <h2>Common Seasonal Illnesses to Watch Out For</h2>
                            <p>
                                Knowing the symptoms of common seasonal ailments helps you detect early warning signs and seek timely medical care:
                            </p>

                            <div class="disease-list">
                                <!-- Viral Fever & Flu -->
                                <div class="disease-card flu-card">
                                    <div class="disease-card-header">
                                        <div class="disease-title-wrap">
                                            <div class="disease-icon" style="background:#eff6ff; color:#2563eb;"><i class="fas fa-head-side-cough"></i></div>
                                            <h3 class="disease-title">Viral Fever and Flu</h3>
                                        </div>
                                        <span class="disease-badge" style="background:#dbeafe; color:#1e40af;">Most Common</span>
                                    </div>
                                    <p class="disease-desc">
                                        This is the most frequent complaint in the OPD, presenting with fever, body ache, sore throat, runny nose, and profound fatigue. Most cases settle within three to five days with supportive care. However, flu can be significantly more serious in young children, older adults, pregnant women, and individuals with diabetes or chronic heart and lung conditions.
                                    </p>
                                </div>

                                <!-- Dengue -->
                                <div class="disease-card dengue-card">
                                    <div class="disease-card-header">
                                        <div class="disease-title-wrap">
                                            <div class="disease-icon" style="background:#fee2e2; color:#dc2626;"><i class="fas fa-mosquito"></i></div>
                                            <h3 class="disease-title">Dengue Fever</h3>
                                        </div>
                                        <span class="disease-badge" style="background:#fee2e2; color:#991b1b;">Needs Monitoring</span>
                                    </div>
                                    <p class="disease-desc">
                                        Transmitted by the <em>Aedes</em> mosquito, dengue typically presents with sudden high-grade fever, severe retro-orbital headache (pain behind the eyes), intense joint and muscle aches ("breakbone fever"), and sometimes a measles-like skin rash.
                                    </p>
                                    <div class="disease-warning-callout">
                                        <i class="fas fa-exclamation-triangle"></i>
                                        <span><strong>Important:</strong> If dengue is suspected, strictly avoid ibuprofen, aspirin, and other NSAIDs as they increase the risk of severe internal bleeding. Only paracetamol should be taken under medical guidance.</span>
                                    </div>
                                </div>

                                <!-- Malaria & Chikungunya -->
                                <div class="disease-card malaria-card">
                                    <div class="disease-card-header">
                                        <div class="disease-title-wrap">
                                            <div class="disease-icon" style="background:#fef3c7; color:#d97706;"><i class="fas fa-microscope"></i></div>
                                            <h3 class="disease-title">Malaria and Chikungunya</h3>
                                        </div>
                                        <span class="disease-badge" style="background:#fef3c7; color:#92400e;">Vector-Borne</span>
                                    </div>
                                    <p class="disease-desc">
                                        Malaria often causes cyclical high fever accompanied by severe chills and sweating rigors. Chikungunya causes debilitating joint swelling and pain that can persist for weeks or even months. Because clinical symptoms overlap, a prompt blood test is the only reliable way to differentiate these vector-borne infections.
                                    </p>
                                </div>

                                <!-- Typhoid & Stomach Infections -->
                                <div class="disease-card stomach-card">
                                    <div class="disease-card-header">
                                        <div class="disease-title-wrap">
                                            <div class="disease-icon" style="background:#d1fae5; color:#059669;"><i class="fas fa-viruses"></i></div>
                                            <h3 class="disease-title">Typhoid and Stomach Infections</h3>
                                        </div>
                                        <span class="disease-badge" style="background:#d1fae5; color:#065f46;">Water &amp; Food Borne</span>
                                    </div>
                                    <p class="disease-desc">
                                        Prolonged fever, persistent abdominal pain, vomiting, and loose motions (diarrhoea) can rapidly lead to electrolyte imbalance and severe dehydration, especially in young children and senior citizens.
                                    </p>
                                </div>

                                <!-- Allergies & Breathing Problems -->
                                <div class="disease-card allergy-card">
                                    <div class="disease-card-header">
                                        <div class="disease-title-wrap">
                                            <div class="disease-icon" style="background:#f3e8ff; color:#7c3aed;"><i class="fas fa-lungs"></i></div>
                                            <h3 class="disease-title">Allergies and Breathing Problems</h3>
                                        </div>
                                        <span class="disease-badge" style="background:#f3e8ff; color:#5b21b6;">Respiratory</span>
                                    </div>
                                    <p class="disease-desc">
                                        Dust, pollen, and post-monsoon smog irritate hypersensitive airways, triggering incessant sneezing, persistent dry or phlegm cough, and chest wheezing. Individuals with pre-existing asthma or COPD often experience sudden symptom exacerbations.
                                    </p>
                                </div>
                            </div>
                        </section>

                        <!-- Section 3: When to See a Doctor -->
                        <section id="when-to-see-doctor" class="article-section">
                            <h2>When Should You See a Doctor?</h2>
                            <p>
                                While many viral illnesses resolve on their own, delaying treatment in serious cases can lead to complications. Consult a physician promptly if you or a family member experience any of the following warning signs:
                            </p>

                            <div class="doctor-warning-box">
                                <div class="doctor-warning-title">
                                    <i class="fas fa-exclamation-circle"></i> Prompt Doctor Visit Checklist
                                </div>
                                <ul class="symptom-checklist">
                                    <li><i class="fas fa-check-circle"></i> Fever that lasts more than 2 to 3 days or keeps rising</li>
                                    <li><i class="fas fa-check-circle"></i> Severe body ache, joint pain, or an unyielding headache</li>
                                    <li><i class="fas fa-check-circle"></i> Persistent vomiting, severe abdominal pain or loose motions</li>
                                    <li><i class="fas fa-check-circle"></i> Red spots on the skin (petechiae), or bleeding from gums or nose</li>
                                    <li><i class="fas fa-check-circle"></i> Breathlessness, persistent wheezing, or chest tightness</li>
                                    <li><i class="fas fa-check-circle"></i> Unusual weakness, drowsiness, or significantly reduced urine output</li>
                                    <li><i class="fas fa-check-circle"></i> In children: poor feeding, excessive sleepiness, or continuous inconsolable crying</li>
                                </ul>

                                <div class="emergency-banner-alert">
                                    <i class="fas fa-ambulance"></i>
                                    <div>
                                        <strong>Emergency Alert:</strong> Severe symptoms such as active bleeding, acute breathlessness, or mental confusion require emergency medical care right away at our 24x7 Emergency Centre.
                                    </div>
                                </div>
                            </div>
                        </section>

                        <!-- Section 4: Ways to Stay Healthy -->
                        <section id="prevention-tips" class="article-section">
                            <h2>Simple Ways to Stay Healthy This Season</h2>
                            <p>
                                Simple, consistent preventive habits can protect your family from most seasonal illnesses:
                            </p>

                            <div class="prevention-grid">
                                <div class="prevention-item">
                                    <div class="prevention-icon"><i class="fas fa-shield-virus"></i></div>
                                    <h4>Stop Mosquito Breeding</h4>
                                    <p>Empty and scrub air coolers, flower pots, and open buckets at least once a week. Use mosquito repellents, window meshes, and bed nets.</p>
                                </div>

                                <div class="prevention-item">
                                    <div class="prevention-icon"><i class="fas fa-glass-whiskey"></i></div>
                                    <h4>Stay Well Hydrated</h4>
                                    <p>Drink plenty of clean filtered or boiled water, fresh coconut water, and warm vegetable soups to support immune detoxification.</p>
                                </div>

                                <div class="prevention-item">
                                    <div class="prevention-icon"><i class="fas fa-apple-alt"></i></div>
                                    <h4>Eat Immunity-Rich Foods</h4>
                                    <p>Include seasonal fruits rich in vitamin C such as amla (Indian gooseberry), oranges, and guavas, alongside a wholesome home-cooked diet.</p>
                                </div>

                                <div class="prevention-item">
                                    <div class="prevention-icon"><i class="fas fa-hands-wash"></i></div>
                                    <h4>Practise Strict Hygiene</h4>
                                    <p>Wash hands frequently with soap, drink only RO-filtered or boiled water, and strictly avoid uncovered street foods and cut fruits.</p>
                                </div>

                                <div class="prevention-item">
                                    <div class="prevention-icon"><i class="fas fa-head-side-mask"></i></div>
                                    <h4>Protect Your Lungs</h4>
                                    <p>Check the daily Air Quality Index (AQI), wear an N95 mask on high-pollution days, and keep your prescribed rescue inhaler accessible if you have asthma.</p>
                                </div>

                                <div class="prevention-item">
                                    <div class="prevention-icon"><i class="fas fa-syringe"></i></div>
                                    <h4>Get the Flu Vaccine</h4>
                                    <p>An annual influenza vaccination is strongly recommended for children, older adults, pregnant women, and people with chronic health conditions.</p>
                                </div>
                            </div>
                        </section>

                        <!-- Section 5: Avoid Self-Medication -->
                        <section id="avoid-self-medication" class="article-section">
                            <h2>Avoid Self-Medication: Why It Can Be Risky</h2>
                            <div class="caution-box">
                                <div class="caution-title">
                                    <i class="fas fa-prescription-bottle-alt"></i> Beware of Leftover Antibiotics &amp; Painkillers
                                </div>
                                <p>
                                    Taking leftover antibiotics or over-the-counter painkillers at the first sign of fever is common but extremely risky. Antibiotics are completely ineffective against viral infections and contribute to antibiotic resistance. Furthermore, common pain medications like ibuprofen, aspirin, or diclofenac can cause dangerous platelet dysfunction and internal bleeding in dengue cases.
                                </p>
                                <p style="margin-top: 10px;">
                                    A physician's timely assessment and a simple complete blood count (CBC) test are the safest, most effective way to start the correct treatment right from day one.
                                </p>
                            </div>
                        </section>

