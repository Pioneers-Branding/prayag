                                                <span class="fast-letter">A</span>
                                                <span class="fast-text">Arm Weakness</span>
                                            </div>
                                            <div class="fast-item">
                                                <span class="fast-letter">S</span>
                                                <span class="fast-text">Speech Difficulty</span>
                                            </div>
                                            <div class="fast-item">
                                                <span class="fast-letter">T</span>
                                                <span class="fast-text">Time to Call</span>
                                            </div>
                                        </div>
                                    </div>
                                </div>

                                <!-- Sign 4 -->
                                <div class="sign-card">
                                    <div class="sign-number">04</div>
                                    <div class="sign-body">
                                        <h3>Sudden, Severe Headache ("Thunderclap Headache")</h3>
                                        <p>A headache that strikes with abrupt intensity and feels like the "worst headache of your life", particularly accompanied by vomiting, stiff neck, altered vision, or confusion, may indicate an aneurysm or bleeding in the brain (intracranial hemorrhage).</p>
                                    </div>
                                </div>

                                <!-- Sign 5 -->
                                <div class="sign-card">
                                    <div class="sign-number">05</div>
                                    <div class="sign-body">
                                        <h3>Uncontrolled Bleeding</h3>
                                        <p>Bleeding that does not subside after applying direct, firm pressure for 10 minutes, or massive blood loss from any open laceration, road accident, or wound, is a critical emergency. Apply pressure and reach an emergency department in Noida without delay.</p>
                                    </div>
                                </div>

                                <!-- Sign 6 -->
                                <div class="sign-card">
                                    <div class="sign-number">06</div>
                                    <div class="sign-body">
                                        <h3>Severe Abdominal Pain</h3>
                                        <p>Intense, excruciating, or sudden stomach pain, especially when paired with high fever, continuous vomiting, abdominal rigidity, or a swollen belly, can signal acute appendicitis, bowel obstruction, perforated ulcer, or internal hemorrhage that demands urgent surgical triage.</p>
                                    </div>
                                </div>

                                <!-- Sign 7 -->
                                <div class="sign-card">
                                    <div class="sign-number">07</div>
                                    <div class="sign-body">
                                        <h3>Loss of Consciousness or Fainting (Syncope)</h3>
                                        <p>Fainting episodes, sudden blackouts, disorientation, or unresponsiveness should never be brushed aside. They frequently indicate underlying cardiac arrhythmias, severe neurological issues, or acute blood pressure drops requiring immediate clinical assessment.</p>
                                    </div>
                                </div>

                                <!-- Sign 8 -->
                                <div class="sign-card">
                                    <div class="sign-number">08</div>
                                    <div class="sign-body">
                                        <h3>Serious Injury from an Accident or Fall</h3>
                                        <p>Road accidents, major falls, crush injuries, and head impacts require prompt <strong>accident and emergency care</strong>. Even if the person seems alert initially, internal bleeding, spinal trauma, or brain concussions can manifest hours later. A rapid CT scan and trauma evaluation rules out hidden danger.</p>
                                    </div>
                                </div>

                                <!-- Sign 9 -->
                                <div class="sign-card">
                                    <div class="sign-number">09</div>
                                    <div class="sign-body">
                                        <h3>Severe Allergic Reaction (Anaphylaxis)</h3>
                                        <p>Rapid swelling of the face, lips, tongue, or throat, dizziness, wheezing, or widespread hives following food ingestion, medication, or an insect sting can obstruct airways within minutes. Immediate emergency administration of epinephrine and life support is crucial.</p>
                                    </div>
                                </div>

                                <!-- Sign 10 -->
                                <div class="sign-card">
                                    <div class="sign-number">10</div>
                                    <div class="sign-body">
                                        <h3>High Fever with Confusion or Seizures</h3>
                                        <p>A spiking high fever combined with neck stiffness, delirium, convulsions (seizures), lethargy, or purple skin rashes can indicate severe infections such as meningitis, encephalitis, or sepsis. In children and seniors especially, these signs mandate urgent hospital admission.</p>
                                    </div>
                                </div>

