                        <!-- Section: 10 Warning Signs -->
                        <section id="ten-warning-signs" class="article-section">
                            <h2>10 Warning Signs You Should Never Ignore</h2>
                            <p>
                                If you or someone with you experiences any of the following symptoms, seek <strong>emergency care in Noida</strong> immediately:
                            </p>

                            <div class="signs-container">
                                
                                <!-- Sign 1 -->
                                <div class="sign-card">
                                    <div class="sign-number">01</div>
                                    <div class="sign-body">
                                        <h3>Chest Pain or Pressure</h3>
                                        <p>Sudden chest pain, tightness, heaviness, or burning pressure, especially if it spreads to the left arm, shoulder, neck, jaw or back, can signal an acute myocardial infarction (heart attack). Do not wait to see if it eases. Seek immediate cardiac emergency intervention.</p>
                                    </div>
                                </div>

                                <!-- Sign 2 -->
                                <div class="sign-card">
                                    <div class="sign-number">02</div>
                                    <div class="sign-body">
                                        <h3>Difficulty Breathing</h3>
                                        <p>Sudden shortness of breath, gasping for air, wheezing, or feeling like you cannot get enough oxygen can point to a cardiac event, pulmonary embolism, severe asthma attack, or anaphylaxis. Any sudden trouble breathing needs urgent hospital evaluation.</p>
                                    </div>
                                </div>

                                <!-- Sign 3 -->
                                <div class="sign-card">
                                    <div class="sign-number">03</div>
                                    <div class="sign-body">
                                        <h3>Signs of a Stroke (Think FAST)</h3>
                                        <p>Slurred speech, sudden numbness or paralysis on one side of the face or body, sudden loss of balance, or acute confusion are hallmark signs of a stroke. Time is brain cells—fast medical clot-busting treatment can prevent lasting paralysis or disability.</p>
                                        
                                        <div class="fast-stroke-box">
                                            <div class="fast-item">
                                                <span class="fast-letter">F</span>
