                            <p>
                                When an emergency strikes, staying calm and acting decisively makes all the difference in patient outcomes. Follow these vital emergency guidelines:
                            </p>

                            <div class="action-checklist">
                                <h3><i class="fas fa-clipboard-check"></i> Essential Emergency Protocol</h3>
                                <ul class="checklist-items">
                                    <li>
                                        <i class="fas fa-phone-alt"></i>
                                        <span><strong>Call for help immediately:</strong> Contact our 24x7 emergency helpline (0120 4021900) or dispatch an Advanced Life Support (ALS) ambulance.</span>
                                    </li>
                                    <li>
                                        <i class="fas fa-bed"></i>
                                        <span><strong>Keep the patient still & comfortable:</strong> Avoid giving oral fluids or food, which could cause choking if surgery or sedation is needed.</span>
                                    </li>
                                    <li>
                                        <i class="fas fa-hand-holding-medical"></i>
                                        <span><strong>For bleeding:</strong> Apply clean, continuous direct pressure to the wound with a sterile gauze or clean cloth.</span>
                                    </li>
                                    <li>
                                        <i class="fas fa-heart"></i>
                                        <span><strong>Suspected heart attack or stroke:</strong> Do NOT attempt to drive yourself. Keep the patient calm, sitting upright, and wait for emergency medical transport.</span>
                                    </li>
                                    <li>
                                        <i class="fas fa-file-medical"></i>
                                        <span><strong>Carry critical medical records:</strong> If easily accessible, bring ID, recent prescriptions, discharge summaries, and a list of known allergies.</span>
                                    </li>
                                </ul>
